export function resolveLanguage(language?: string, hassLanguage?: string): string {
  const selected = !language || language === 'auto' ? hassLanguage : language;
  const code = (selected || 'en').replace(/["']/g, '').replace(/_/g, '-').split('-')[0].toLowerCase();
  return STRINGS[code] ? code : 'en';
}

export function localize(key: string, language?: string): string {
  return STRINGS[resolveLanguage(language)][key] ?? STRINGS.en[key] ?? key;
}
